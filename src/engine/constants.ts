export type SpinRule = "T-spins" | "all-mini+";

export interface GameOptions {
  seed: number;
  g: number; // rows per frame
  gincrease: number; // added to g per second after gmargin (frames)
  gmargin: number;
  locktime: number; // frames
  lockresets: number;
  nextcount: number;
  allow180: boolean;
  spinbonuses: SpinRule;
  b2bchaining: boolean;
  nolockout: boolean;
  hasgarbage: boolean;
  garbagespeed: number; // frames an incoming attack travels before it can enter
  garbagecap: number; // max lines tanked per piece
  garbagemultiplier: number;
  garbageincrease: number; // added to the multiplier per second after garbagemargin
  garbagemargin: number;
  messiness_change: number; // chance the hole moves between attacks
  allclear_garbage: number;
  levels: boolean; // blitz-style leveling
  levelspeed: number;
  levelgbase: number;
  levelgspeed: number;
  objective: { type: "none" } | { type: "lines"; count: number } | { type: "timed"; frames: number };
}

