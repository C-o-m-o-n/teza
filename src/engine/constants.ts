// Gameplay constants. Values were read out of the official TETR.IO client
// (tetrio.js, build 20260714) so behaviour matches; the data layout is our own.
// Coordinate system: x grows right, y grows DOWN. Kick offsets use the same axes.

export type PieceType = "z" | "l" | "o" | "s" | "i" | "j" | "t";
export type Cell = PieceType | "g" | null; // g = garbage
export type Rotation = 0 | 1 | 2 | 3;

export const PIECES: PieceType[] = ["z", "l", "o", "s", "i", "j", "t"]; // bag order before shuffle

interface PieceDef {
  size: number; // bounding box edge
  dx: number; // box origin offset: cell (c, r) lands at (x + c - dx, ceil(y + r - dy))
  dy: number;
  spawn: [number, number][]; // cells in rotation 0, as [col, row]
}

const DEFS: Record<PieceType, PieceDef> = {
  z: { size: 3, dx: 1, dy: 1, spawn: [[0, 0], [1, 0], [1, 1], [2, 1]] },
  l: { size: 3, dx: 1, dy: 1, spawn: [[2, 0], [0, 1], [1, 1], [2, 1]] },
  o: { size: 2, dx: 0, dy: 1, spawn: [[0, 0], [1, 0], [0, 1], [1, 1]] },
  s: { size: 3, dx: 1, dy: 1, spawn: [[1, 0], [2, 0], [0, 1], [1, 1]] },
  i: { size: 4, dx: 1, dy: 1, spawn: [[0, 1], [1, 1], [2, 1], [3, 1]] },
  j: { size: 3, dx: 1, dy: 1, spawn: [[0, 0], [0, 1], [1, 1], [2, 1]] },
  t: { size: 3, dx: 1, dy: 1, spawn: [[1, 0], [0, 1], [1, 1], [2, 1]] },
};

export interface Shape {
  dx: number;
  dy: number;
  cells: [number, number][];
}

function rotateCW(cells: [number, number][], size: number): [number, number][] {
  return cells.map(([c, r]) => [size - 1 - r, c]);
}

// SHAPES[type][rotation] — rotations generated by spinning the bounding box clockwise,
// which reproduces the official matrices exactly.
export const SHAPES: Record<PieceType, Shape[]> = Object.fromEntries(
  PIECES.map((p) => {
    const def = DEFS[p];
    const rots: Shape[] = [];
    let cells = def.spawn;
    for (let r = 0; r < 4; r++) {
      rots.push({ dx: def.dx, dy: def.dy, cells: p === "o" ? def.spawn : cells });
      cells = rotateCW(cells, def.size);
    }
    return [p, rots];
  }),
) as Record<PieceType, Shape[]>;

